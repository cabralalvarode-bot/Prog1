package de.tha.wi1;

public class Task01 {

	public static void main(String[] args) {
        
		char c1 = 80; // Decimal 80 -> 'P'
		char c2 = 0b1110010; // Binario 1110010 (prefijo 0b) -> 'r' (decimal 114)
		char c3 = 111; // Decimal 111 -> 'o'
		char c4 = 0x67; // Hexadecimal 67 (prefijo 0x) -> 'g' (decimal 103)
		char c5 = 061; // Oktal 61 (prefijo 0) -> '1' (decimal 49)

		System.out.print(c1);
		System.out.print(c2);
		System.out.print(c3);
		System.out.print(c4);
		System.out.print(c5);
			
	}
	
}
